-- Add sensible baseline departments to existing tenants without replacing any
-- tenant-created records. Passwords remain unset until an administrator sets
-- them from department management.
WITH department_templates(
    "name",
    "code",
    "slug",
    "type",
    "category",
    "shortName",
    "description"
) AS (
    VALUES
      ('Reception', 'RECEPTION', 'reception', 'OPD'::"public"."DepartmentType", 'ADMINISTRATIVE'::"public"."DepartmentCategory", 'REC', 'Front desk and patient intake hub.'),
      ('Administration', 'ADMIN', 'administration', 'CUSTOM'::"public"."DepartmentType", 'ADMINISTRATIVE'::"public"."DepartmentCategory", 'ADM', 'Administrative coordination and operations.'),
      ('Outpatient Department', 'OPD', 'outpatient-department', 'OPD'::"public"."DepartmentType", 'CLINICAL'::"public"."DepartmentCategory", 'OPD', 'Primary consultations and outpatient clinical services.'),
      ('Nursing Unit', 'NURSING', 'nursing-unit', 'INPATIENT_WARD'::"public"."DepartmentType", 'CLINICAL'::"public"."DepartmentCategory", 'NUR', 'Ward-based patient care and continuity of service.'),
      ('Pharmacy', 'PHARMACY', 'pharmacy', 'PHARMACY'::"public"."DepartmentType", 'CLINICAL_SUPPORT'::"public"."DepartmentCategory", 'PHARM', 'Medication management and dispensing support.'),
      ('Laboratory', 'LAB', 'laboratory', 'LABORATORY'::"public"."DepartmentType", 'DIAGNOSTICS'::"public"."DepartmentCategory", 'LAB', 'Diagnostics and test processing.'),
      ('Radiology', 'RAD', 'radiology', 'RADIOLOGY'::"public"."DepartmentType", 'DIAGNOSTICS'::"public"."DepartmentCategory", 'RAD', 'Imaging and interpretation services.'),
      ('Billing & Finance', 'BILLING', 'billing-finance', 'BILLING_FINANCE'::"public"."DepartmentType", 'ADMINISTRATIVE'::"public"."DepartmentCategory", 'FIN', 'Financial operations and revenue management.'),
      ('Housekeeping', 'HOUSEKEEPING', 'housekeeping', 'HOUSEKEEPING_INFECTION_CONTROL'::"public"."DepartmentType", 'SUPPORT'::"public"."DepartmentCategory", 'HK', 'Environmental hygiene and safety support controls.')
),
created_departments AS (
    INSERT INTO "public"."departments" (
        "id",
        "tenantId",
        "name",
        "code",
        "slug",
        "type",
        "category",
        "shortName",
        "description",
        "status",
        "requiresDepartmentPassword",
        "autoGeneratedFeatures",
        "dashboardConfig",
        "sidebarConfig",
        "workflowConfig",
        "settings",
        "createdAt",
        "updatedAt"
    )
    SELECT
        gen_random_uuid(),
        tenant."id",
        template."name",
        template."code",
        template."slug",
        template."type",
        template."category",
        template."shortName",
        template."description",
        'ACTIVE'::"public"."RecordStatus",
        false,
        jsonb_build_object(
            'type', template."type",
            'category', template."category",
            'enabledPages', jsonb_build_array('Overview', 'Queue', 'Staff', 'Reports'),
            'modules', jsonb_build_array('dashboard', 'staff', 'queue', 'reports'),
            'generatedBy', 'revaltrix-default-tenant-bootstrap'
        ),
        jsonb_build_object(
            'layout', 'command-center',
            'widgets', jsonb_build_array('overview', 'queue', 'staff', 'alerts'),
            'refreshIntervalSeconds', 20
        ),
        jsonb_build_object(
            'groups', jsonb_build_array(
                jsonb_build_object('label', 'Core', 'items', jsonb_build_array('Overview', 'Queue', 'Staff', 'Reports'))
            )
        ),
        jsonb_build_object(
            'stages', jsonb_build_array('Intake', 'Process', 'Review', 'Close')
        ),
        jsonb_build_object(
            'departmentType', template."type",
            'category', template."category",
            'requiresDepartmentPassword', false
        ),
        CURRENT_TIMESTAMP,
        CURRENT_TIMESTAMP
    FROM "public"."tenants" AS tenant
    CROSS JOIN department_templates AS template
    WHERE tenant."deletedAt" IS NULL
      AND NOT (
          tenant."type" IN (
              'PHARMACY'::"public"."TenantType",
              'LABORATORY'::"public"."TenantType",
              'RADIOLOGY_CENTER'::"public"."TenantType"
          )
          AND template."code" IN ('NURSING', 'RECEPTION')
      )
    ON CONFLICT ("tenantId", "code") DO NOTHING
    RETURNING "id"
)
SELECT COUNT(*) FROM created_departments;
